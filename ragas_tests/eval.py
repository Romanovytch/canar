"""
Ragas demo — what the library does and how it applies to our project.

Run:
    cp .env.example .env   # fill in LLM credentials
    python -m venv .venv && source .venv/bin/activate
    pip install -r requirements.txt
    python eval.py
"""

import os
from pathlib import Path

HERE = Path(__file__).parent

import pandas as pd
from dotenv import load_dotenv
from langchain_openai import ChatOpenAI, OpenAIEmbeddings
from ragas import evaluate, EvaluationDataset
from ragas.dataset_schema import SingleTurnSample
from ragas.metrics import Faithfulness, ResponseRelevancy, FactualCorrectness
from ragas.run_config import RunConfig

load_dotenv()

# ---------------------------------------------------------------------------
# STEP 1 — Configure the LLM
#
# Ragas uses an LLM internally to "judge" the quality of RAG outputs.
# It sends structured prompts like:
#   "Given this context, is this answer faithful? yes/no"
# and parses the response into a numeric score.
#
# In our project: this would be the same Mistral endpoint that canar uses
# to generate answers — we just reuse it here as the evaluator.
# ---------------------------------------------------------------------------

llm = ChatOpenAI(
    model=os.environ["LLM_MODEL"],
    openai_api_base=os.environ["LLM_API_BASE"],
    openai_api_key=os.environ["LLM_API_KEY"],
    temperature=0.0,
)

embeddings = OpenAIEmbeddings(
    model=os.environ["EMBED_MODEL"],
    openai_api_base=os.environ["EMBED_API_BASE"],
    openai_api_key=os.environ.get("EMBED_API_KEY", "EMPTY"),
)


# ---------------------------------------------------------------------------
# STEP 2 — Define the evaluation dataset
#
# Each sample represents one RAG interaction with four fields:
#
#   user_input         → the question the user asked
#   retrieved_contexts → list of text chunks retrieved from the vector store
#   response           → the answer generated by the LLM
#   reference          → the ideal / expected answer (ground truth)
#
# In our project:
#   user_input         ← query typed in canar's chat UI
#   retrieved_contexts ← chunks that Qdrant returned (ingested by agora)
#   response           ← what Mistral generated based on those chunks
#   reference          ← would need to be written by a domain expert once
# ---------------------------------------------------------------------------

SAMPLES = [
    SingleTurnSample(
        user_input="How do I read a CSV file in R?",
        retrieved_contexts=[
            "In R, you can read CSV files using read.csv() from base R or read_csv() "
            "from the readr package. The read_csv() function is faster and returns a "
            "tibble. You can specify the delimiter with the sep= argument.",
        ],
        response=(
            "To read a CSV file in R, use read.csv('file.csv') from base R or "
            "readr::read_csv('file.csv') from tidyverse. Both accept a sep= argument "
            "to set the delimiter."
        ),
        reference="Use read.csv() from base R or readr::read_csv() from tidyverse.",
    ),
    SingleTurnSample(
        user_input="What is the difference between a data.frame and a tibble?",
        retrieved_contexts=[
            "A tibble is a modern reimagining of the data.frame, provided by the tibble "
            "package (part of tidyverse). Unlike data.frames, tibbles never convert "
            "strings to factors, print only the first 10 rows by default, and preserve "
            "column names exactly as given.",
        ],
        response=(
            "A tibble is similar to a data.frame but with better defaults: it never "
            "converts strings to factors and prints a compact preview. It is the default "
            "data structure in tidyverse packages."
        ),
        reference=(
            "Tibbles come from the tidyverse, do not coerce strings to factors, "
            "and have a cleaner print method than data.frames."
        ),
    ),
    SingleTurnSample(
        user_input="How do I join two tables in R?",
        retrieved_contexts=[
            "Base R provides merge() for joining data frames. The dplyr package offers "
            "more expressive join functions: left_join(), inner_join(), right_join(), and "
            "full_join(). The by= argument specifies which columns to join on.",
            # Intentionally irrelevant second chunk to test context precision
            "The ggplot2 package is used to create data visualizations using a layered "
            "grammar of graphics.",
        ],
        response=(
            "You can join tables in R with merge() from base R, or with left_join() / "
            "inner_join() from dplyr. Use the by= argument to specify the key columns."
        ),
        reference=(
            "Use merge() in base R or dplyr's left_join()/inner_join() with the by= argument."
        ),
    ),
]


# ---------------------------------------------------------------------------
# STEP 3 — Choose metrics
#
# Ragas ships several metrics; each targets a different failure mode:
#
#   Faithfulness       → is the answer grounded in the retrieved context?
#                        Catches hallucinations: the LLM inventing facts not
#                        present in the retrieved chunks.
#
#   ResponseRelevancy  → is the answer relevant to the question?
#                        Catches evasive or off-topic responses.
#
#   FactualCorrectness → does the answer match the reference (ground truth)?
#                        Requires a human-written reference answer.
#
# In our project:
#   Faithfulness is the most critical — if canar's answer mentions something
#   not in the utilitR chunks, it's either hallucinating or retrieving the
#   wrong chunks (an agora chunking/embedding issue).
# ---------------------------------------------------------------------------

METRICS = [
    Faithfulness(),
    ResponseRelevancy(),
    FactualCorrectness(),
]


# ---------------------------------------------------------------------------
# STEP 4 — Run evaluation
#
# evaluate() feeds each sample through every metric and aggregates scores.
# Each score is between 0 and 1 (higher = better).
# The LLM is called internally by ragas to judge each sample.
# ---------------------------------------------------------------------------

def main():
    dataset = EvaluationDataset(samples=SAMPLES)

    print(f"Evaluating {len(SAMPLES)} samples with {len(METRICS)} metrics...\n")
    results = evaluate(
        dataset=dataset,
        metrics=METRICS,
        llm=llm,
        embeddings=embeddings,
        run_config=RunConfig(timeout=300, max_workers=2),
    )

    df = results.to_pandas()
    print("Columns:", df.columns.tolist())
    score_cols = [c for c in df.columns if c not in ("user_input", "retrieved_contexts", "response", "reference")]
    print(df[["user_input"] + score_cols].to_string(index=False))
    print(f"\nMean scores:\n{df[score_cols].mean().to_string()}")

    out = HERE / "experiments" / "results.csv"
    out.parent.mkdir(exist_ok=True)
    df.to_csv(out, index=False)
    print(f"\nFull results saved to {out}")


if __name__ == "__main__":
    main()
